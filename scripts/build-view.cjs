#!/usr/bin/env node
'use strict';
// Generates lib/view.cjs from lib/view.mjs.
//
// view.mjs is the one fold. The Node tools (ck.cjs, render.cjs) are CommonJS and
// require() it, and the viewer page gets the same functions through SHARED
// (f.toString()), so the .cjs has to exist — but as output, not as a second copy
// to keep in step. The transform is deliberately dumb: drop `export ` from each
// function declaration and add the CommonJS wrapper. Anything the transform
// cannot carry over (an import, any other kind of export) fails the build
// instead of producing a file that quietly differs.
//
//   node scripts/build-view.cjs

const fs = require('fs');
const path = require('path');

const LIB = path.join(__dirname, '..', 'lib');
const SRC = path.join(LIB, 'view.mjs');
const OUT = path.join(LIB, 'view.cjs');

const HEADER = "'use strict';\n" +
  '// GENERATED by scripts/build-view.cjs from lib/view.mjs — edit that file, not this one.\n' +
  '// What these functions are, and the rules they keep, is written at the top of view.mjs.\n';

// view.mjs opens with a comment written for its own readers ("this is the canonical
// source … edit here"). Copied into the output it would say the opposite of HEADER, so
// the output starts at the first function instead.
const LEAD_COMMENT = /^\/\*[\s\S]*?\*\/\s*/;

const FOOTER = `const SHARED = [esc, chainOf, divergence, foldEvents, metrics, renderTree, renderK]
  .map(function (f) { return f.toString(); }).join('\\n\\n');

module.exports = { esc, chainOf, divergence, foldEvents, metrics, renderTree, renderK, SHARED };
`;

const fail = (msg) => { console.error(`build-view: ${msg}`); process.exit(1); };

const src = fs.readFileSync(SRC, 'utf8');

if (/^\s*import[\s({*"']/m.test(src)) {
  fail('view.mjs has an import; the generated .cjs would not resolve it');
}
const stray = src.split('\n').filter((l) => /^\s*export\b/.test(l) && !/^export function \w+\(/.test(l));
if (stray.length) {
  fail(`view.mjs may only export function declarations; found: ${stray[0].trim()}`);
}

// A function exported from the .mjs but missing from the footer would vanish from
// the .cjs and break the Node tools at call time, not here — so check it here.
const exported = [...src.matchAll(/^export function (\w+)\(/gm)].map((m) => m[1]);
const listed = FOOTER.match(/module\.exports = \{([^}]*)\}/)[1];
const missing = exported.filter((n) => !new RegExp(`\\b${n}\\b`).test(listed));
if (missing.length) {
  fail(`not in the generated module.exports (add to FOOTER): ${missing.join(', ')}`);
}

const body = src
  .replace(LEAD_COMMENT, '')
  .replace(/^export function /gm, 'function ')
  .replace(/\s+$/, '');
fs.writeFileSync(OUT, `${HEADER}\n${body}\n\n${FOOTER}`);
console.log(`wrote lib/view.cjs (${exported.length} functions)`);
